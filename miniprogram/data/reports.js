// 30 天学习地图: 按弱项优先 (分数升序), 每天聚焦一个细颗粒度动作
// v0.8.6 起优先取 ACTION_DICT 的具体动作, 不足时回退到 LEARNING_TIPS
function learningMap(dimScores, abilityScores) {
  const sorted = DIMS
    .map((d) => ({ dim: d, score: dimScores[d.id] || 0, weight: d.weight || 1 }))
    .sort((a, b) => a.score - b.score);

  const map = [];
  let day = 1;
  sorted.forEach((d) => {
    // 从能力点分数中找本维度最弱的点
    let weakAbility = null;
    let weakScore = Infinity;
    if (abilityScores && abilityScores[d.dim.id]) {
      Object.keys(abilityScores[d.dim.id]).forEach((k) => {
        const s = abilityScores[d.dim.id][k];
        if (s < weakScore) { weakScore = s; weakAbility = k; }
      });
    }
    let item;
    if (weakAbility && ACTION_DICT[d.dim.id] && ACTION_DICT[d.dim.id][weakAbility]) {
      const act = ACTION_DICT[d.dim.id][weakAbility][0];
      item = { dim: d.dim.id, dimName: d.dim.name, t: 'Day ' + day, ability: weakAbility, actionTitle: act.t, actionDetail: act.d };
    } else {
      // 兜底: 取模板
      const tip = LEARNING_TIPS[d.dim.id][(day - 1) % 5];
      item = { dim: d.dim.id, dimName: d.dim.name, t: 'Day ' + day, actionTitle: '本维度动作', actionDetail: tip };
    }
    map.push(item);
    day++;
  });
  return map;
}

