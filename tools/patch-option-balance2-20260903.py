LINE_RE = re.compile(r'^(\s*)"([ABCD])":\s*"(.*?)"(,?)\s*$')
ID_RE = re.compile(r'"id":\s*"([A-Z0-9-]+)"')

total = 0
for fname, qmap in OVERRIDES.items():
    fpath = ROOT / "miniprogram" / "data" / fname
    lines = fpath.read_text(encoding="utf-8").splitlines(keepends=True)
    cur_q, applied = None, set()
    for i, line in enumerate(lines):
        m = ID_RE.search(line)
        if m:
            cur_q = m.group(1); continue
        om = LINE_RE.match(line.rstrip("\n"))
        if om and cur_q in qmap:
            indent, key, val, comma = om.groups()
            if key not in qmap[cur_q]: continue
            new = qmap[cur_q][key]
            if val.startswith("“") and not new.startswith("“"):
                new = "“" + new + "”"
            lines[i] = f'{indent}"{key}": "{new}"{comma}\n'
            applied.add((cur_q, key)); total += 1
    missing = [(q, k) for q in qmap for k in "ABCD" if (q, k) not in applied]
    if missing:
        print(f"[FAIL] {fname} 未匹配: {missing[:5]}"); sys.exit(1)
    fpath.write_text("".join(lines), encoding="utf-8")
    print(f"[OK] {fname}: {len(applied)} 处已替换")
print(f"共替换 {total} 处")
